def parse(s):
    v = np.array([(float(a), float(b) * 1e-4) for a, b in re.findall(r"(\d\.\d{4})\((\d+)\)", s)])
    return v[:, 0], v[:, 1]


def pull(s, s_hmc):
    (a, da), (b, db) = parse(s), parse(s_hmc)
    return (a - b) / np.hypot(da, db)


